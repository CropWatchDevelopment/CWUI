#!/usr/bin/env node
// Renders scripts/style-guide/style-guide.html to static/cropwatch-style-guide.pdf
// with headless Chromium. Colours and sizes come from the library token files,
// so re-run this (`npm run style-guide`) whenever tokens change.
//
// Chromium is found via $CHROME_PATH, then the Playwright browser cache, then
// google-chrome / chromium on PATH.

import { execFileSync, spawnSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '../..');
const outFile = join(root, 'static', 'cropwatch-style-guide.pdf');

// ── Data the page can't read itself (file:// can't fetch JSON) ──────────
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const metricSource = readFileSync(join(root, 'src/lib/utils/metricColors.ts'), 'utf8');

const METRIC_LABELS = {
	TEMPERATURE: 'Air temperature',
	SOIL_TEMPERATURE: 'Soil temperature',
	HUMIDITY: 'Humidity',
	SOIL_MOISTURE: 'Soil moisture',
	RAIN: 'Rain',
	DEW_POINT: 'Dew point',
	CO2: 'CO₂',
	LIGHT: 'Light / PAR',
	SOIL_EC: 'Soil EC',
	VPD: 'VPD',
	PRESSURE: 'Pressure'
};

const metrics = [];
const metricPattern = /const (\w+): MetricColor = \{ color: '(#[0-9a-fA-F]{6})'(, gradient: true)? \}/g;
for (const [, name, color, gradient] of metricSource.matchAll(metricPattern)) {
	metrics.push({ label: METRIC_LABELS[name] ?? name, color, gradient: Boolean(gradient) });
}
if (metrics.length === 0) {
	throw new Error('No metric colours found in metricColors.ts; update the pattern in build.mjs.');
}

// Static logo: the site logo fades its leaves in with SMIL <animate>, which a
// print capture would catch at opacity 0. Strip the animation, show the leaves.
const logo = readFileSync(join(root, 'static', 'cropwatch_animated.svg'), 'utf8')
	.replace(/<animate\b[^>]*>(<\/animate>)?/g, '')
	.replace(/(<circle[^>]*class="leaf"[^>]*?)opacity="0"/g, '$1opacity="1"');
writeFileSync(join(here, 'logo-static.svg'), logo);

const generated = {
	version: `v${pkg.version}`,
	date: new Date().toLocaleDateString('en-GB', { year: 'numeric', month: 'long', day: 'numeric' }),
	metrics
};
writeFileSync(
	join(here, 'generated.js'),
	`// Generated by build.mjs. Do not edit.\nwindow.CW_GUIDE = ${JSON.stringify(generated, null, '\t')};\n`
);

// ── Find Chromium ───────────────────────────────────────────────────────
function findChrome() {
	if (process.env.CHROME_PATH && existsSync(process.env.CHROME_PATH)) return process.env.CHROME_PATH;

	const cache = join(homedir(), '.cache', 'ms-playwright');
	if (existsSync(cache)) {
		const candidates = readdirSync(cache)
			.filter((d) => /^chromium-\d+$/.test(d))
			.sort((a, b) => Number(b.split('-')[1]) - Number(a.split('-')[1]));
		for (const dir of candidates) {
			for (const sub of ['chrome-linux64/chrome', 'chrome-linux/chrome', 'chrome-mac/Chromium.app/Contents/MacOS/Chromium']) {
				const p = join(cache, dir, sub);
				if (existsSync(p)) return p;
			}
		}
	}

	for (const bin of ['google-chrome', 'google-chrome-stable', 'chromium', 'chromium-browser']) {
		const found = spawnSync('which', [bin], { encoding: 'utf8' });
		if (found.status === 0 && found.stdout.trim()) return found.stdout.trim();
	}
	throw new Error('Chromium not found. Set CHROME_PATH or run `npx playwright install chromium`.');
}

const chrome = findChrome();
const pageUrl = pathToFileURL(join(here, 'style-guide.html')).href;

execFileSync(
	chrome,
	[
		'--headless=new',
		'--no-sandbox',
		'--disable-gpu',
		'--hide-scrollbars',
		'--no-pdf-header-footer',
		'--run-all-compositor-stages-before-draw',
		// Gives web fonts and the page script time to finish before printing.
		'--virtual-time-budget=20000',
		`--print-to-pdf=${outFile}`,
		pageUrl
	],
	{ stdio: ['ignore', 'ignore', 'pipe'] }
);

const size = statSync(outFile).size;
console.log(`Style guide written to ${outFile} (${Math.round(size / 1024)} KB) using ${chrome}`);
